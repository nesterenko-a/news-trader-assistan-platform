"""Справочник переименованных тикеров Мосбиржи.

Некоторые бумаги меняют тикер на бирже (напр. X5 Group: старый тикер `FIVE`
не торгуется, актуальный — `X5`). При актуализации котировок, если по запрошенному
тикеру MOEX не отдаёт данных, пробуем актуальный тикер из этого словаря.
"""

RENAMED_TICKERS: dict[str, str] = {
    "FIVE": "X5",  # X5 Group (ретейл) — тикер сменён на X5
}


def actual_ticker(ticker: str) -> str:
    """Возвращает актуальный биржевой тикер, если известен маппинг, иначе исходный."""
    return RENAMED_TICKERS.get(ticker.strip().upper(), ticker.strip().upper())
